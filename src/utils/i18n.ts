let currentLanguage: 'sw' | 'en' = 'sw';

export const setLanguage = (lang: 'sw' | 'en') => {
  currentLanguage = lang;
};

export const getLanguage = (): 'sw' | 'en' => currentLanguage;

export const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
  const lang = translations[currentLanguage] as Record<string, string>;
  let text = lang[key] ?? (translations.sw as Record<string, string>)[key] ?? key;
  if (vars) {
    const keys = Object.keys(vars) as Array<keyof typeof vars>;
    keys.forEach((k) => {
      text = text.replace(`{${String(k)}}`, String(vars[k]));
    });
  }
  return text;
};
